#!/usr/bin/env python3
"""Build the flag atlas used by the server badges.

Downloads the public-domain flag images from https://flagcdn.com, packs them
into a padded grid and writes:

  apps/protogrid-desktop/assets/flags.rgba   raw RGBA atlas
  apps/protogrid-desktop/src/flags.rs        atlas geometry + country codes

Requires Pillow (`pip install pillow`). Run from the repository root:

    ./scripts/gen-flags.py
"""

from __future__ import annotations

import io
import json
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ASSET = ROOT / "apps" / "protogrid-desktop" / "assets" / "flags.rgba"
MODULE = ROOT / "apps" / "protogrid-desktop" / "src" / "flags.rs"

FLAG_WIDTH = 24
FLAG_HEIGHT = 18
PAD = 1
CELL_WIDTH = FLAG_WIDTH + PAD * 2
CELL_HEIGHT = FLAG_HEIGHT + PAD * 2
COLUMNS = 18
FROM_SIZE = "24x18"


def fetch(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": "ProtoGrid/flag-builder"})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read()


def build() -> None:
    catalogue = json.loads(fetch("https://flagcdn.com/en/codes.json"))
    codes = sorted(code for code in catalogue if len(code) == 2 and code.isalpha())
    rows = (len(codes) + COLUMNS - 1) // COLUMNS
    atlas = Image.new("RGBA", (COLUMNS * CELL_WIDTH, rows * CELL_HEIGHT), (0, 0, 0, 0))

    for index, code in enumerate(codes):
        data = fetch(f"https://flagcdn.com/{FROM_SIZE}/{code}.png")
        flag = Image.open(io.BytesIO(data)).convert("RGBA")
        if flag.size != (FLAG_WIDTH, FLAG_HEIGHT):
            flag = flag.resize((FLAG_WIDTH, FLAG_HEIGHT), Image.LANCZOS)
        left = (index % COLUMNS) * CELL_WIDTH + PAD
        top = (index // COLUMNS) * CELL_HEIGHT + PAD
        atlas.alpha_composite(flag, (left, top))
        # Repeat the edge pixels into the padding so linear filtering cannot
        # sample a neighbouring flag when the texture is drawn scaled down.
        atlas.paste(atlas.crop((left, top, left + FLAG_WIDTH, top + 1)), (left, top - 1))
        atlas.paste(
            atlas.crop((left, top + FLAG_HEIGHT - 1, left + FLAG_WIDTH, top + FLAG_HEIGHT)),
            (left, top + FLAG_HEIGHT),
        )
        atlas.paste(atlas.crop((left, top, left + 1, top + FLAG_HEIGHT)), (left - 1, top))
        atlas.paste(
            atlas.crop((left + FLAG_WIDTH - 1, top, left + FLAG_WIDTH, top + FLAG_HEIGHT)),
            (left + FLAG_WIDTH, top),
        )
        print(f"  {code} {catalogue[code]}", file=sys.stderr)

    ASSET.parent.mkdir(parents=True, exist_ok=True)
    # Written raw because the Rust side wraps the bytes into an egui texture
    # without an image decoder. `.save()` would pick a container from the
    # extension (SGI for `.rgba`), so dump the pixels directly.
    ASSET.write_bytes(atlas.tobytes())
    width, height = atlas.size

    lines = [
        "//! Flag atlas for the server badges.",
        "//!",
        "//! Generated by `scripts/gen-flags.py` from https://flagcdn.com",
        "//! (public-domain flag images). Do not edit by hand.",
        "",
        f"pub const FLAG_WIDTH: u32 = {FLAG_WIDTH};",
        f"pub const FLAG_HEIGHT: u32 = {FLAG_HEIGHT};",
        f"pub const CELL_WIDTH: u32 = {CELL_WIDTH};",
        f"pub const CELL_HEIGHT: u32 = {CELL_HEIGHT};",
        f"pub const ATLAS_COLUMNS: u32 = {COLUMNS};",
        f"pub const ATLAS_WIDTH: u32 = {width};",
        f"pub const ATLAS_HEIGHT: u32 = {height};",
        "",
        'pub static ATLAS_RGBA: &[u8] = include_bytes!("../assets/flags.rgba");',
        "",
        "/// Lower-case ISO 3166-1 alpha-2 codes, sorted to allow binary search.",
        "pub static CODES: &[&str] = &[",
    ]
    for code in codes:
        lines.append(f'    "{code}",')
    lines += [
        "];",
        "",
        "/// Returns the row-major index of a country in the atlas.",
        "pub fn index(code: &str) -> Option<usize> {",
        "    let code = code.trim();",
        "    if code.len() != 2 || !code.bytes().all(|byte| byte.is_ascii_alphabetic()) {",
        "        return None;",
        "    }",
        "    let code = code.to_ascii_lowercase();",
        "    CODES.binary_search(&code.as_str()).ok()",
        "}",
        "",
    ]
    MODULE.write_text("\n".join(lines), encoding="utf-8")
    if shutil.which("rustfmt"):
        subprocess.run(["rustfmt", "--edition", "2021", str(MODULE)], check=True)
    print(f"wrote {ASSET} ({width}x{height}) and {MODULE}", file=sys.stderr)


if __name__ == "__main__":
    build()
